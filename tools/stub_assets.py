#!/usr/bin/env python3
"""Write zeroed stand-ins for the extracted assets into the build directory, for SM64_ASSET_STUBS
(CI without a baserom): an empty file for every missing #include "*.inc.c", the cake textures, and
asset_stubs.c with the symbols that only sources generated from extracted files define. The
executable links but does not run. Usage: stub_assets.py <build dir>"""
import os, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = Path(sys.argv[1]).resolve()
os.chdir(ROOT)

bare = {}
for d in ("actors", "bin", "data", "levels", "sound", "src", "text"):
    for f in Path(d).rglob("*.c"):
        for eq, inc in re.findall(r'(=?)\s*#include\s+"([^"]+\.inc\.c)"', f.read_text(errors="ignore")):
            # text/ is generated by textconv from committed sources.
            if not inc.startswith("text/") and not Path(inc).exists() and not (f.parent / inc).exists():
                bare[inc] = bare.get(inc, False) or bool(eq)
for inc in sorted(bare):
    p = BUILD / inc
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("{ 0 }\n" if bare[inc] else "")  # a bare `x =` initializer needs a value

# skyconv writes cake.inc.c as definitions, not as an initializer body.
cake = sorted(set(re.findall(r"\bcake_end_texture_\d+\b", Path("levels/ending/leveldata.c").read_text())))
(BUILD / "levels/ending/cake.inc.c").write_text(
    "".join(f"ALIGNED8 static const Texture {t}[] = {{ 0 }};\n" for t in cake))

# gDemoInputs comes from the extracted demo files; the skybox tables from the skybox PNGs.
skies = re.findall(r"extern SkyboxTexture (\w+);", Path("src/game/skybox.c").read_text())
(BUILD / "asset_stubs.c").write_text('#include "types.h"\n\nu8 gDemoInputs[1];\n'
                                     + "".join(f"const u8 *const {s}[80];\n" for s in skies))
print(f"stub_assets: {len(bare)} empty bodies, {len(cake)} cake textures, {len(skies)} skyboxes")
